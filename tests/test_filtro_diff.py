import pytest

from revisor.dominio.filtro_diff import e_ruido, filtrar_arquivos
from tests.fakes import DIFF_SERVICE, arquivo


@pytest.mark.parametrize("caminho", [
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock", "Pipfile.lock", "composer.lock",
])
def test_lockfiles_sao_ruido(caminho):
    assert e_ruido(caminho) is True


@pytest.mark.parametrize("caminho", ["app.min.js", "app.min.css", "vendor.bundle.js", "app.js.map"])
def test_arquivos_minificados_sao_ruido(caminho):
    assert e_ruido(caminho) is True


@pytest.mark.parametrize("caminho", [
    "vendor/lib.js", "node_modules/pacote/index.js", "dist/bundle.js", "frontend/dist/app.js",
])
def test_pastas_vendorizadas_sao_ruido(caminho):
    assert e_ruido(caminho) is True


@pytest.mark.parametrize("cabecalho", [
    "// @generated by tool\nclass X {}",
    "/* auto-generated */\nclass X {}",
    "-- DO NOT EDIT\ncreate table x();",
])
def test_cabecalho_de_arquivo_gerado_e_ruido(cabecalho):
    assert e_ruido("src/X.java", cabecalho) is True


def test_marcador_fora_das_5_primeiras_linhas_nao_conta():
    cabecalho = "\n".join(["linha normal"] * 5 + ["// @generated"])
    assert e_ruido("src/X.java", cabecalho) is False


def test_migration_marcada_como_gerada_nao_e_removida():
    assert e_ruido("db/migrations/V1__init.sql", "-- DO NOT EDIT\ncreate table x();") is False
    assert e_ruido("src/main/migration/V2.sql", "-- auto-generated") is False


def test_arquivo_normal_nao_e_ruido():
    assert e_ruido("src/ContratoService.java", "public class ContratoService {}") is False


def test_nunca_ignorar_resgata_um_lockfile():
    assert e_ruido("package-lock.json", nunca_ignorar=("package-lock.json",)) is False


def test_ignorar_extra_do_perfil_remove_algo_a_mais():
    assert e_ruido("src/gerado/Proxy.java", ignorar_extra=("src/gerado/*",)) is True
    assert e_ruido("src/normal/Outro.java", ignorar_extra=("src/gerado/*",)) is False


def test_filtrar_arquivos_separa_mantidos_e_ignorados_preservando_ordem():
    arquivos = [
        arquivo("package-lock.json", DIFF_SERVICE),
        arquivo("src/A.java", DIFF_SERVICE),
        arquivo("vendor/lib.js", DIFF_SERVICE),
        arquivo("src/B.java", DIFF_SERVICE),
    ]
    mantidos, ignorados = filtrar_arquivos(arquivos)
    assert [a.caminho_novo for a in mantidos] == ["src/A.java", "src/B.java"]
    assert ignorados == ["package-lock.json", "vendor/lib.js"]


def test_diff_so_com_ruido_fica_vazio_apos_filtro():
    arquivos = [arquivo("package-lock.json", DIFF_SERVICE)]
    mantidos, ignorados = filtrar_arquivos(arquivos)
    assert mantidos == [] and ignorados == ["package-lock.json"]
